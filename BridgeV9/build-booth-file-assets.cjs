'use strict';
const fs=require('node:fs');
const path=require('node:path');

const files=['campaign-content.json','project-settings.json','education.html','changelog.json','credits.json'];
const assets=Object.fromEntries(files.map(file=>[
  file,fs.readFileSync(path.join(__dirname,file),'utf8').replace(/^\uFEFF/,'')
]));
const script=`// Generated by build-booth-file-assets.cjs.
'use strict';
const boothFileAssets=${JSON.stringify(assets)};
function readBoothFileAsset(file){
  if(!Object.hasOwn(boothFileAssets,file))throw new Error('로컬 데이터 없음: '+file);
  const source=boothFileAssets[file];
  return file.endsWith('.json')?JSON.parse(source):source;
}
`;
fs.writeFileSync(path.join(__dirname,'booth-file-assets.js'),script);
